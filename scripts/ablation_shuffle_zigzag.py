"""Shuffle ablation: classify from zigzag vectorizations of shuffled grids.

Requires shuffles generated by generate_trials_ablation_shuffle.py.  Runs the
same classification problems as classify_zigzag.py, once per shuffle, using
the shuffled vectorization caches instead of the original ones.  The same
shuffle IDs are used for all mice (sampled from the IDs available for every
mouse with ``--shuffle-seed``, or given with ``--shuffle-ids``).

Output: results/ablation_shuffle/zigzag/<vectorization>/<model>/<shuffle>-<mode>/
        p<P>-<per-trial|global>/<target>_<scope>/<run>/shuffle-NNNN/
"""

from __future__ import annotations

import argparse
import sys
import traceback
from pathlib import Path

from classification_data import build_problems
from classification_engine import (
    grid_type,
    results_base,
    MODEL_TITLES,
    VECTOR_MODELS,
    Tee,
    TrainConfig,
    add_output_args,
    add_problem_args,
    add_training_args,
    base_config,
    configure_torch,
    default_run_name,
    fit_predict_vector,
    problem_config_from_args,
    run_and_save,
    thresh_tag,
)
from classification_features import SHUFFLE_TYPES, ShuffleSource, sample_shuffle_ids
from utils import _opt_csv_list, _opt_int, _str2bool


def add_shuffle_args(p: argparse.ArgumentParser) -> None:
    g = p.add_argument_group("shuffles")
    g.add_argument("--shuffle-type", default="time", choices=SHUFFLE_TYPES)
    g.add_argument("--different-shuffle-per-trial", default=True, type=_str2bool)
    g.add_argument("--n-shuffles", default=None, type=int, help="Number of shuffle IDs to sample")
    g.add_argument("--shuffle-ids", default=None, type=_opt_csv_list, help="Explicit shuffle IDs (overrides --n-shuffles)")
    g.add_argument("--shuffle-seed", default=42, type=int, help="Seed for sampling shuffle IDs")
    g.add_argument(
        "--generation-clip-frames",
        default=240,
        type=_opt_int,
        help="clip_frames used when the shuffles were generated (part of the cache names)",
    )


def resolve_shuffle_ids(args: argparse.Namespace, source: ShuffleSource, mice) -> list:
    available = source.common_ids(mice)
    if args.shuffle_ids is not None:
        wanted = [int(v) for v in args.shuffle_ids]
        missing = [v for v in wanted if v not in available]
        if missing:
            raise RuntimeError(f"Shuffle IDs {missing} are not available for every mouse (common: {available})")
        return wanted
    if args.n_shuffles is None:
        raise RuntimeError("Give --n-shuffles or --shuffle-ids")
    return sample_shuffle_ids(available, args.n_shuffles, args.shuffle_seed)


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_problem_args(p)
    g = p.add_argument_group("zigzag features")
    g.add_argument("--vectorization", default="Turnover")
    g.add_argument("--p-active", required=True, type=int)
    g.add_argument("--per-trial-thresh", required=True, type=_str2bool)
    g.add_argument("--cache-dir", default=None, type=Path)
    add_shuffle_args(p)
    p.add_argument("--model", default="logreg", choices=VECTOR_MODELS)
    p.add_argument("--init-seed", default=42, type=int)
    add_training_args(p)
    add_output_args(p)
    return p


def main() -> int:
    args = build_parser().parse_args()
    problem_cfg = problem_config_from_args(args)
    train_cfg = TrainConfig.from_args(args)

    source = ShuffleSource(
        data_root=args.data_root,
        shuffle_type=args.shuffle_type,
        different_shuffle_per_trial=args.different_shuffle_per_trial,
        method=args.vectorization,
        p_active=args.p_active,
        per_trial_thresh=args.per_trial_thresh,
        generation_clip=args.generation_clip_frames,
        cache_dir=args.cache_dir,
    )
    run_dir = args.output_dir or (
        results_base(args)
        / "ablation_shuffle"
        / "zigzag"
        / args.vectorization
        / args.model
        / f"{args.shuffle_type}-{source.mode}"
        / thresh_tag(args.p_active, args.per_trial_thresh)
        / f"{args.target}_{args.scope}"
        / (args.run_name or default_run_name())
    )
    run_dir.mkdir(parents=True, exist_ok=True)

    problems = build_problems(problem_cfg)
    if not problems.units:
        print(f"No classification problems could be built. Skips: {problems.skips}", file=sys.stderr)
        return 1
    shuffle_ids = resolve_shuffle_ids(args, source, problems.mice_used)
    print(f"Shuffle IDs: {shuffle_ids}")
    device = configure_torch(train_cfg) if args.model != "logreg" else None

    for shuffle_id in shuffle_ids:
        out_dir = run_dir / f"shuffle-{shuffle_id:04d}"
        out_dir.mkdir(parents=True, exist_ok=True)
        with Tee(out_dir / "run.log"):
            try:
                print(f"ablation_shuffle_zigzag: {args.target} / {args.scope} / {args.shuffle_type}-{source.mode} / shuffle {shuffle_id}")
                features = source.zigzag_features(shuffle_id)

                def fit_fn_for_unit(unit):
                    x = features.features(unit.samples)
                    return lambda tr, te, seed: fit_predict_vector(
                        args.model,
                        x,
                        unit.y,
                        tr,
                        te,
                        n_classes=unit.n_classes,
                        window_frames=unit.window_frames,
                        seed=seed,
                        train_cfg=train_cfg,
                        device=device,
                    )

                context = {
                    "grid_type": grid_type(args),
                    "target": args.target,
                    "scope": args.scope,
                    "input": "zigzag",
                    "vectorization": args.vectorization,
                    "model": args.model,
                    "p_active": args.p_active,
                    "thresh_mode": "per-trial" if args.per_trial_thresh else "global",
                    "shuffle_type": args.shuffle_type,
                    "shuffle_mode": source.mode,
                    "shuffle_id": shuffle_id,
                    "init_seed": args.init_seed,
                    "split_seed": args.split_seed,
                }

                def make_config():
                    config = base_config(args, problem_cfg, train_cfg if args.model != "logreg" else None)
                    config.update(
                        {
                            "context": context,
                            "shuffles": {**source.to_dict(), "shuffle_ids": shuffle_ids},
                            "notes": problems.notes,
                            "mice_used": problems.mice_used,
                            "feature_caches": features.sources,
                        }
                    )
                    return config

                run_and_save(
                    problems.units,
                    fit_fn_for_unit,
                    init_seed=args.init_seed,
                    out_dir=out_dir,
                    context=context,
                    make_config=make_config,
                    skips=problems.skips,
                    resume=args.resume,
                    title=(
                        f"{args.target} {args.scope} | shuffled ({args.shuffle_type}-{source.mode} #{shuffle_id}) "
                        f"zigzag {args.vectorization} {thresh_tag(args.p_active, args.per_trial_thresh)} | "
                        f"{MODEL_TITLES[args.model]}"
                    ),
                )
            except Exception:
                traceback.print_exc()
                return 1
    print(f"\nDone: {run_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
