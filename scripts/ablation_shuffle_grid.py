"""Shuffle ablation: classify shuffled grids with a 3D-CNN.

Requires shuffles generated by generate_trials_ablation_shuffle.py, which
saves the shuffled grids next to the shuffled vectorization caches.  Their
folder names include the zigzag configuration used at generation time, so
``--gen-p-active``, ``--gen-per-trial-thresh``, ``--gen-vectorization`` and
``--generation-clip-frames`` locate them; the grids themselves do not depend
on it.  Runs the same problems as classify_grid.py once per shuffle.

Output: results/ablation_shuffle/grid/<model>/<shuffle>-<mode>/<target>_<scope>/<run>/shuffle-NNNN/
"""

from __future__ import annotations

import argparse
import sys
import traceback
from pathlib import Path

from ablation_shuffle_zigzag import add_shuffle_args, resolve_shuffle_ids
from classification_data import build_problems
from classification_engine import (
    grid_type,
    results_base,
    GRID_MODELS,
    MODEL_TITLES,
    Tee,
    TrainConfig,
    add_output_args,
    add_problem_args,
    add_training_args,
    base_config,
    configure_torch,
    default_run_name,
    fit_predict_grid,
    problem_config_from_args,
    run_and_save,
)
from classification_features import ShuffleSource, grid_dataset
from utils import _str2bool


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    add_problem_args(p)
    add_shuffle_args(p)
    g = p.add_argument_group("shuffle generation configuration (locates the shuffled grids)")
    g.add_argument("--gen-vectorization", default="Turnover")
    g.add_argument("--gen-p-active", required=True, type=int)
    g.add_argument("--gen-per-trial-thresh", default=True, type=_str2bool)
    g.add_argument("--cache-dir", default=None, type=Path)
    p.add_argument("--model", default="cnn3d_raw", choices=GRID_MODELS)
    p.add_argument("--init-seed", default=42, type=int)
    add_training_args(p)
    add_output_args(p)
    return p


def main() -> int:
    args = build_parser().parse_args()
    problem_cfg = problem_config_from_args(args)
    train_cfg = TrainConfig.from_args(args)

    source = ShuffleSource(
        data_root=args.data_root,
        shuffle_type=args.shuffle_type,
        different_shuffle_per_trial=args.different_shuffle_per_trial,
        method=args.gen_vectorization,
        p_active=args.gen_p_active,
        per_trial_thresh=args.gen_per_trial_thresh,
        generation_clip=args.generation_clip_frames,
        cache_dir=args.cache_dir,
    )
    run_dir = args.output_dir or (
        results_base(args)
        / "ablation_shuffle"
        / "grid"
        / args.model
        / f"{args.shuffle_type}-{source.mode}"
        / f"{args.target}_{args.scope}"
        / (args.run_name or default_run_name())
    )
    run_dir.mkdir(parents=True, exist_ok=True)

    problems = build_problems(problem_cfg)
    if not problems.units:
        print(f"No classification problems could be built. Skips: {problems.skips}", file=sys.stderr)
        return 1
    shuffle_ids = resolve_shuffle_ids(args, source, problems.mice_used)
    print(f"Shuffle IDs: {shuffle_ids}")
    device = configure_torch(train_cfg)
    normalize = args.model == "cnn3d_norm"

    for shuffle_id in shuffle_ids:
        out_dir = run_dir / f"shuffle-{shuffle_id:04d}"
        out_dir.mkdir(parents=True, exist_ok=True)
        with Tee(out_dir / "run.log"):
            try:
                print(f"ablation_shuffle_grid: {args.target} / {args.scope} / {args.shuffle_type}-{source.mode} / shuffle {shuffle_id}")

                def fit_fn_for_unit(unit):
                    paths = source.grid_paths(unit.samples, shuffle_id)
                    ds = grid_dataset(unit.samples, unit.y, normalize=normalize, grid_paths=paths)
                    return lambda tr, te, seed: fit_predict_grid(
                        args.model,
                        ds,
                        unit.y,
                        tr,
                        te,
                        n_classes=unit.n_classes,
                        seed=seed,
                        train_cfg=train_cfg,
                        device=device,
                    )

                context = {
                    "grid_type": grid_type(args),
                    "target": args.target,
                    "scope": args.scope,
                    "input": "grid",
                    "vectorization": "",
                    "model": args.model,
                    "p_active": None,
                    "thresh_mode": "",
                    "shuffle_type": args.shuffle_type,
                    "shuffle_mode": source.mode,
                    "shuffle_id": shuffle_id,
                    "init_seed": args.init_seed,
                    "split_seed": args.split_seed,
                }

                def make_config():
                    config = base_config(args, problem_cfg, train_cfg)
                    config.update(
                        {
                            "context": context,
                            "shuffles": {**source.to_dict(), "shuffle_ids": shuffle_ids},
                            "notes": problems.notes,
                            "mice_used": problems.mice_used,
                            "device": str(device),
                        }
                    )
                    return config

                run_and_save(
                    problems.units,
                    fit_fn_for_unit,
                    init_seed=args.init_seed,
                    out_dir=out_dir,
                    context=context,
                    make_config=make_config,
                    skips=problems.skips,
                    resume=args.resume,
                    title=(
                        f"{args.target} {args.scope} | shuffled grid ({args.shuffle_type}-{source.mode} "
                        f"#{shuffle_id}) | {MODEL_TITLES[args.model]}"
                    ),
                )
            except Exception:
                traceback.print_exc()
                return 1
    print(f"\nDone: {run_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
